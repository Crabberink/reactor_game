pub struct VoxelMeshingPlugin;
impl Plugin for VoxelMeshingPlugin {
    fn build(&self, app: &mut App) {
        app.add_plugins(MaterialPlugin::<VoxelMaterial>::default());
        app.add_systems(Update, queue_generate_chunk_mesh.run_if(in_state(LoadingState::Loaded)));
        app.add_systems(Update, collect_generated_chunk_meshes.run_if(in_state(LoadingState::Loaded)));
    }
}

#[derive(Component)]
#[component(storage = "SparseSet")]
pub struct DirtyChunkMesh;

#[derive(Component, Deref, DerefMut)]
#[component(storage = "SparseSet")]
pub struct MeshGenTask(Task<Option<Mesh>>);

const MAX_QUEUE_PER_FRAME: usize = 8;

pub fn queue_generate_chunk_mesh(
    shared_registry: Res<SharedBlockRegistry>,
    chunk_map: Res<ChunkMap>,
    mut commands: Commands,
    chunks: Query<&Chunk>,
    dirty_chunks: Query<(Entity, &Chunk), (With<DirtyChunkMesh>, Without<MeshGenTask>)>,
    loaders: Query<&Position, With<ChunkLoader>>,
) {
    let pool = AsyncComputeTaskPool::get();

    let _s = info_span!("queue_generate_chunk_mesh").entered();

    let mut ungenerated_chunks: Vec<_> = dirty_chunks.iter().collect();
    ungenerated_chunks.sort_by_key(|(_, c)| {
        loaders.iter()
            .map(|pos| (c.coord - world_to_chunk(pos.0)).length_squared())
            .min()
            .unwrap_or(i32::MAX)
    });

    for (entity, chunk) in ungenerated_chunks.into_iter().take(MAX_QUEUE_PER_FRAME) {
        let registry_handle = shared_registry.clone();

        let chunk = chunk.clone();
        // Fuck you because why can't I use [None; 6]
        let mut neighbors: [Option<Chunk>; 6] = [None, None, None, None, None, None];

        for (i, n) in ChunkNeighbor::iter().enumerate() {
            let adj_pos = chunk.coord + n.adj_offset();

            neighbors[i] = chunk_map.chunks.get(&adj_pos)
                .and_then(|&entity| { chunks.get(entity).ok().and_then(|c| Some(c.clone()) ) });
        }

        let mesh_task = pool.spawn(async move {
            let _s = info_span!("gen_mesh_task").entered();
            build_mesh(&chunk, neighbors, &registry_handle)
        });

        commands.entity(entity)
            .remove::<DirtyChunkMesh>()
            .insert(MeshGenTask(mesh_task));
    }
}

pub fn collect_generated_chunk_meshes(
    mut tasks: Query<(Entity, &mut MeshGenTask)>,
    mut meshes: ResMut<Assets<Mesh>>,
    mut commands: Commands,
    chunk_material: Res<ChunkMaterialRes>
) {
    let _s = info_span!("collect_generated_chunk_meshes").entered();

    for (entity, mut task) in &mut tasks {
        let Some(optional_mesh) = check_ready(&mut task.0) else { continue };

        commands.entity(entity).try_remove::<MeshGenTask>();

        let Some(mesh) = optional_mesh else {
            commands.entity(entity).try_remove::<Mesh3d>();
            continue;
        };

        if let Some(aabb) = mesh.get_aabb() {
            commands.entity(entity)
                .try_insert(aabb);
        }

        let _s = info_span!("add_mesh").entered();

        commands.entity(entity)
            .try_insert(Mesh3d(meshes.add(mesh)))
            .try_insert(MeshMaterial3d(chunk_material.0.clone()));
    }
}

// generated by claude using my original version (I had to add the const N declaration and reorder the params cause its lwk slow)
fn is_solid(
    chunk: &Chunk,
    pos: IVec3,
    neighbors: &[Option<Chunk>; 6],
    registry: &BlockRegistry,
) -> bool {
    const N: i32 = CHUNK_SIZE as i32;

    let out = IVec3::new(
        (pos.x >= N) as i32 - (pos.x < 0) as i32,
        (pos.y >= N) as i32 - (pos.y < 0) as i32,
        (pos.z >= N) as i32 - (pos.z < 0) as i32,
    );

    let source: &Chunk = if out == IVec3::ZERO {
        chunk
    } else {
        let Some(n) = ChunkNeighbor::from_offset(out) else { return false }; // diagonal
        let Some(c) = &neighbors[n as usize] else { return false };           // not loaded
        c
    };

    let id = source.get_voxel(pos.rem_euclid(IVec3::splat(N)));
    let Some(def) = registry.get_def(id) else {
        warn!("Treating nonexistent block id: {} as transparent!", id);
        return false;
    };

    !(def.empty || def.transparent)
}

fn build_mesh(chunk: &Chunk, neighbors: [Option<Chunk>; 6], registry: &BlockRegistry) -> Option<Mesh> {
    let mut mesh = Mesh::new(PrimitiveTopology::TriangleList, RenderAssetUsages::RENDER_WORLD);

    let mut positions: Vec<[f32; 3]> = Vec::new();
    let mut normals: Vec<[f32; 3]> = Vec::new();
    let mut uvs: Vec<[f32; 2]> = Vec::new();
    let mut indices: Vec<u32> = Vec::new();

    for x in 0..CHUNK_SIZE {
        for y in 0..CHUNK_SIZE {
            for z in 0..CHUNK_SIZE {
                let id = chunk.get_voxel_xyz(x,y,z);
                let Some(def) = registry.get_def(id) else {
                    warn!("Skipping nonexistent block id: {}!", id);
                    continue;
                };

                if def.empty { continue; }

                if id != 0 {
                    let mut base = positions.len() as u32;

                    let offset = Vec3::new(
                        x as f32 * VOXEL_SIZE,
                        y as f32 * VOXEL_SIZE,
                        z as f32 * VOXEL_SIZE,
                    );

                    for face in VoxelFace::iter() {
                        let ipos = IVec3::new(x as i32, y as i32, z as i32);
                        let adj_pos: IVec3 = ipos + face.adj_offset();
                        if is_solid(chunk, adj_pos, &neighbors, registry) { continue; }

                        let face_data = generate_voxel_face(face, offset);

                        let face_uvs = [
                            [def.uv_rect.min.x, def.uv_rect.min.y],
                            [def.uv_rect.max.x, def.uv_rect.min.y],
                            [def.uv_rect.max.x, def.uv_rect.max.y],
                            [def.uv_rect.min.x, def.uv_rect.max.y],
                        ];

                        positions.extend_from_slice(&face_data.positions);
                        normals.extend_from_slice(&face_data.normals);
                        uvs.extend_from_slice(&face_uvs);
                        indices.extend_from_slice(&[
                            base, base + 2, base + 1,
                            base, base + 3, base + 2,
                        ]);

                        base += 4;
                    }
                }
            }
        }
    }

    if indices.is_empty() { return None; }

    mesh.insert_attribute(Mesh::ATTRIBUTE_POSITION, positions);
    mesh.insert_attribute(Mesh::ATTRIBUTE_NORMAL, normals);
    mesh.insert_attribute(Mesh::ATTRIBUTE_UV_0, uvs);
    mesh.insert_indices(Indices::U32(indices));

    Some(mesh)
}

#[derive(EnumIter, Clone, Copy)]
#[repr(u8)]
pub enum ChunkNeighbor {
    Front,
    Right,
    Back,
    Left,
    Top,
    Bottom,
}

impl ChunkNeighbor {
    pub fn adj_offset(&self) -> IVec3 {
        match self {
            ChunkNeighbor::Front => IVec3::new(0, 0, -1),
            ChunkNeighbor::Right => IVec3::new(1, 0, 0),
            ChunkNeighbor::Back => IVec3::new(0, 0, 1),
            ChunkNeighbor::Left => IVec3::new(-1, 0, 0),
            ChunkNeighbor::Top => IVec3::new(0, 1, 0),
            ChunkNeighbor::Bottom => IVec3::new(0, -1, 0),
        }
    }

    pub fn from_offset(o: IVec3) -> Option<Self> {
        match (o.x, o.y, o.z) {
            (0, 0, -1) => Some(Self::Front),
            (1, 0, 0)  => Some(Self::Right),
            (0, 0, 1)  => Some(Self::Back),
            (-1, 0, 0) => Some(Self::Left),
            (0, 1, 0)  => Some(Self::Top),
            (0, -1, 0) => Some(Self::Bottom),
            _ => None, // zero or diagonal
        }
    }
}

#[derive(EnumIter)]
#[repr(u8)]
enum VoxelFace {
    Front,
    Right,
    Back,
    Left,
    Top,
    Bottom,
}

impl VoxelFace {
    fn adj_offset(&self) -> IVec3 {
        match self {
            VoxelFace::Front => IVec3::new(0, 0, -1),
            VoxelFace::Right => IVec3::new(1, 0, 0),
            VoxelFace::Back => IVec3::new(0, 0, 1),
            VoxelFace::Left => IVec3::new(-1, 0, 0),
            VoxelFace::Top => IVec3::new(0, 1, 0),
            VoxelFace::Bottom => IVec3::new(0, -1, 0),
        }
    }
}

// Holds a slice of the mesh data for a single face of a voxel, used for mesh generation
struct VoxelFaceData {
    positions: [[f32; 3]; 4],
    normals: [[f32; 3]; 4],
}

fn generate_voxel_face(face: VoxelFace, offset: Vec3) -> VoxelFaceData {

    let positions: [[f32; 3]; 4];
    let normals: [[f32; 3]; 4];

    match face {
        VoxelFace::Front => {
            positions = [
                [offset.x, offset.y, offset.z],
                [offset.x + VOXEL_SIZE, offset.y, offset.z],
                [offset.x + VOXEL_SIZE, offset.y + VOXEL_SIZE, offset.z],
                [offset.x, offset.y + VOXEL_SIZE, offset.z],
            ];
            normals = [[0.0, 0.0, -1.0]; 4];
        }
        VoxelFace::Right => {
            positions = [
                [offset.x + VOXEL_SIZE, offset.y, offset.z],
                [offset.x + VOXEL_SIZE, offset.y, offset.z + VOXEL_SIZE],
                [offset.x + VOXEL_SIZE, offset.y + VOXEL_SIZE, offset.z + VOXEL_SIZE],
                [offset.x + VOXEL_SIZE, offset.y + VOXEL_SIZE, offset.z],
            ];
            normals = [[1.0, 0.0, 0.0]; 4];
        }
        VoxelFace::Back => {
            positions = [
                [offset.x + VOXEL_SIZE, offset.y, offset.z + VOXEL_SIZE],
                [offset.x, offset.y, offset.z + VOXEL_SIZE],
                [offset.x, offset.y + VOXEL_SIZE, offset.z + VOXEL_SIZE],
                [offset.x + VOXEL_SIZE, offset.y + VOXEL_SIZE, offset.z + VOXEL_SIZE],
            ];
            normals = [[0.0, 0.0, 1.0]; 4];
        }
        VoxelFace::Left => {
            positions = [
                [offset.x, offset.y, offset.z + VOXEL_SIZE],
                [offset.x, offset.y, offset.z],
                [offset.x, offset.y + VOXEL_SIZE, offset.z],
                [offset.x, offset.y + VOXEL_SIZE, offset.z + VOXEL_SIZE],
            ];
            normals = [[-1.0, 0.0, 0.0]; 4];
        }
        VoxelFace::Top => {
            positions = [
                [offset.x, offset.y + VOXEL_SIZE, offset.z],
                [offset.x + VOXEL_SIZE, offset.y + VOXEL_SIZE, offset.z],
                [offset.x + VOXEL_SIZE, offset.y + VOXEL_SIZE, offset.z + VOXEL_SIZE],
                [offset.x, offset.y + VOXEL_SIZE, offset.z + VOXEL_SIZE],
            ];
            normals = [[0.0, 1.0, 0.0]; 4];
        }
        VoxelFace::Bottom => {
            positions = [
                [offset.x, offset.y, offset.z + VOXEL_SIZE],
                [offset.x + VOXEL_SIZE, offset.y, offset.z + VOXEL_SIZE],
                [offset.x + VOXEL_SIZE, offset.y, offset.z],
                [offset.x, offset.y, offset.z],
            ];
            normals = [[0.0, -1.0, 0.0]; 4];
        }
    }

    // What should I do with all the time I've saved not writing return
    VoxelFaceData {
        positions,
        normals,
    }
}

